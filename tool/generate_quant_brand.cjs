const widths = [13,15,15,14,12];
const add=(a,b)=>a.map((v,i)=>v+b[i]);
const sub=(a,b)=>a.map((v,i)=>v-b[i]);
const mul=(a,s)=>a.map(v=>v*s);
const n=v=>Number(v.toFixed(4));
const xy=p=>p.map(n).join(' ');
function cubic(p,t) {
  const u=1-t;
  return [0,1].map(i=>u*u*u*p[0][i]+3*u*u*t*p[1][i]+3*u*t*t*p[2][i]+t*t*t*p[3][i]);
}
function tangent(p,t) {
  const u=1-t;
  return [0,1].map(i=>3*u*u*(p[1][i]-p[0][i])+6*u*t*(p[2][i]-p[1][i])+3*t*t*(p[3][i]-p[2][i]));
}
function edge(segment,side,t) {
  const p=cubic(curves[segment],t), d=tangent(curves[segment],t);
  const r=(widths[segment]*(1-t)+widths[segment+1]*t)/2;
  return add(p,mul([-d[1],d[0]],side*r/Math.hypot(...d)));
}
function derivative(fn,t) {
  const lo=Math.max(0,t-0.00001),hi=Math.min(1,t+0.00001);
  return mul(sub(fn(hi),fn(lo)),1/(hi-lo));
}
// Approximate analytic variable-width offsets with cubic curves, <= .008 units
// sampled deviation on the 108-unit canvas. Caps are circular cubic arcs.
function fit(fn,a=0,b=1,depth=0) {
  const p0=fn(a),p3=fn(b),h=(b-a)/3;
  const p=[p0,add(p0,mul(derivative(fn,a),h)),sub(p3,mul(derivative(fn,b),h)),p3];
  let error=0;
  for(let j=1;j<16;j++) error=Math.max(error,Math.hypot(...sub(cubic(p,j/16),fn(a+(b-a)*j/16))));
  if(error>.008 && depth<10) {
    const mid=(a+b)/2;
    return [...fit(fn,a,mid,depth+1),...fit(fn,mid,b,depth+1)];
  }
  return [p];
}
function cap(center,start,r) {
  const result=[];
  for(let i=0;i<2;i++) {
    const a=start-i*Math.PI/2,b=a-Math.PI/2,k=4/3*Math.tan((b-a)/4);
    const p0=add(center,mul([Math.cos(a),Math.sin(a)],r));
    const p3=add(center,mul([Math.cos(b),Math.sin(b)],r));
    result.push([p0,add(p0,mul([-Math.sin(a),Math.cos(a)],r*k)),sub(p3,mul([-Math.sin(b),Math.cos(b)],r*k)),p3]);
  }
  return result;
}
const left=curves.flatMap((_,i)=>fit(t=>edge(i,1,t)));
const right=curves.flatMap((_,i)=>fit(t=>edge(i,-1,t))).reverse().map(p=>[...p].reverse());
const end=curves.at(-1).at(-1),endNormal=sub(left.at(-1)[3],end);
const start=curves[0][0],startNormal=sub(right.at(-1)[3],start);
const outline=[...left,...cap(end,Math.atan2(endNormal[1],endNormal[0]),widths.at(-1)/2),...right,...cap(start,Math.atan2(startNormal[1],startNormal[0]),widths[0]/2)];
const D='M '+xy(outline[0][0])+' '+outline.map(p=>'C '+p.slice(1).map(xy).join(' ')).join(' ')+' Z';
const svg=(body,view='0 0 108 108',size=108)=>`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${view}">${body}</svg>\n`;
const mark=(color=FG,adaptive=false)=>`<g${adaptive?' transform="translate(54 54) scale('+SCALE+') translate(-54 -54)"':''}><path fill="${color}" d="${D}"/></g>`;
const write=(file,body)=>{
  const dest=path.join(ROOT,file);fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,body);
};
function vector(color,size=108,adaptive=false) {
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_quant_brand.cjs: selected fluid q. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp" android:height="${size}dp"\n    android:viewportWidth="108" android:viewportHeight="108">\n${adaptive?'    <group android:pivotX="54" android:pivotY="54" android:scaleX="'+SCALE+'" android:scaleY="'+SCALE+'">\n':''}    <path android:fillColor="${color}" android:pathData="${D}" />\n${adaptive?'    </group>\n':''}</vector>\n`;
}
